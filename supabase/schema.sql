-- SuroyIloilo content schema
-- Run this once in the Supabase SQL editor (SQL Editor > New query > Run).
--
-- Design notes:
--  * Column names match the app's model JSON keys (see lib/models.dart).
--  * `sort` controls display order in the app.
--  * Icons/categories are stored as short string keys the app maps to glyphs
--    (see iconFromKey / PlaceCategoryX.fromKey in lib/models.dart).
--  * Public read-only access via Row Level Security so the publishable key can
--    fetch content but not modify it. Writes happen through the Supabase
--    dashboard (your admin) or an authenticated admin app later.

create table if not exists places (
  id          text primary key,
  name        text not null,
  category    text not null default 'heritage', -- heritage|museum|landmark|nature|hiddenGem
  area        text,
  rating      numeric default 0,
  reviews     integer default 0,
  description text,
  best_time   text,
  tip         text,
  map_query   text,
  sort        integer default 0
);

create table if not exists foods (
  id          bigint generated by default as identity primary key,
  name        text not null,
  vendor      text,
  area        text,
  price_range text,
  rating      numeric default 0,
  reviews     integer default 0,
  description text,
  must_try    text,
  icon        text default 'restaurant', -- ramen|soup|bakery|seafood|rice|grill...
  sort        integer default 0
);

create table if not exists routes (
  id         bigint generated by default as identity primary key,
  from_label text not null,
  to_label   text not null,
  mode       text,
  mode_icon  text default 'bus', -- walk|van|bus|busFilled
  fare       text,
  time       text,
  steps      jsonb default '[]'::jsonb,
  tip        text,
  sort       integer default 0
);

create table if not exists itinerary_stops (
  id         bigint generated by default as identity primary key,
  time_label text,
  title      text not null,
  subtitle   text,
  fare       text,
  sort       integer default 0
);

create table if not exists events (
  id          bigint generated by default as identity primary key,
  name        text not null,
  category    text,
  schedule    text,
  location    text,
  description text,
  organizer   text,
  sort        integer default 0
);

create table if not exists tips (
  id         bigint generated by default as identity primary key,
  author     text not null,
  from_label text,
  topic      text,
  text       text,
  helpful    integer default 0,
  sort       integer default 0
);

-- Row Level Security: allow anyone (the publishable/anon key) to READ only.
do $$
declare t text;
begin
  foreach t in array array['places','foods','routes','itinerary_stops','events','tips']
  loop
    execute format('alter table %I enable row level security;', t);
    execute format(
      'drop policy if exists "public read %1$s" on %1$s;', t);
    execute format(
      'create policy "public read %1$s" on %1$s for select using (true);', t);
  end loop;
end $$;
